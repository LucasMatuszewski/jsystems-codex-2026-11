import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { randomUUID, createHash } from 'node:crypto';
const base = 'http://127.0.0.1:3001';
const today = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Europe/Warsaw' }).format(new Date());
const form = { requestType: 'Reklamacja', category: 'Smartfon', model: 'Dokładny model nieznany', purchaseDate: today, receiptDate: today, buyerType: 'Konsument', purchaseChannel: 'W salonie', description: 'Syntetyczny opis: telefon sporadycznie wyłącza się podczas rozmowy. Objaw nie jest widoczny na zdjęciu.' };
const image = await readFile(new URL('../../../../assets/example-images/phone-2.jpeg', import.meta.url));
const multipart = new FormData();
for (const [key, value] of Object.entries({ ...form, operationId: randomUUID() })) multipart.set(key, value);
multipart.set('image', new Blob([image], { type: 'image/jpeg' }), 'device.jpeg');
const assessmentResponse = await fetch(`${base}/api/assessment`, { method: 'POST', body: multipart });
assert.equal(assessmentResponse.status, 200);
const assessmentBody = await assessmentResponse.text();
const records = assessmentBody.trim().split('\n').map(JSON.parse);
assert.equal(records.filter(item => item.type === 'result' || item.type === 'error').length, 1);
const { caseToken: token, case: initial } = records.find(item => item.type === 'result');
assert.equal(initial.review.required, true);
assert.equal(initial.assessment.decision.available, false);
assert.equal(initial.assessment.decision.observations.length, 0);
assert.equal(initial.assessment.escalation, null);
const captures = [{ stage: 'assessment', request: { form, imageSha256: createHash('sha256').update(image).digest('hex') }, status: assessmentResponse.status, headers: Object.fromEntries(assessmentResponse.headers), body: assessmentBody }];
const turnId = randomUUID();
for (const intent of ['intake', 'retry']) {
  const input = { caseToken: token, operationId: randomUUID(), turnId, attemptId: randomUUID(), intent };
  const response = await fetch(`${base}/api/chat`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(input) });
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('x-vercel-ai-ui-message-stream'), 'v1');
  const body = await response.text();
  const chunks = body.split('\n').filter(line => line.startsWith('data: ') && line !== 'data: [DONE]').map(line => JSON.parse(line.slice(6)));
  assert.ok(chunks.some(chunk => chunk.type === 'error' && chunk.errorText.includes('Wynik oceny pozostaje dostępny')));
  assert.equal(chunks.some(chunk => chunk.type === 'text-delta'), false);
  assert.ok(body.includes('data: [DONE]'));
  assert.equal(/APICallError|Unauthorized|synthetic-invalid-credential|Bearer/i.test(body), false);
  captures.push({ stage: intent, request: input, status: response.status, headers: Object.fromEntries(response.headers), body });
}
const current = await fetch(`${base}/api/case`, { headers: { 'x-case-token': token } });
const final = await current.json();
assert.equal(final.review.required, true);
assert.deepEqual(final.assessment, initial.assessment);
assert.equal(final.turns.length, 1);
assert.deepEqual(final.turns[0].attempts.map(attempt => attempt.status), ['failed', 'failed']);
assert.equal(final.operation.state, 'failed');
captures.push({ stage: 'reconciled-case', status: current.status, headers: Object.fromEntries(current.headers), body: final });
await fetch(`${base}/api/case`, { method: 'DELETE', headers: { 'x-case-token': token } });
await writeFile(new URL('negative-live-captures.json', import.meta.url), JSON.stringify({ date: new Date().toISOString(), target: base, credentialMode: 'Process-local synthetic invalid credential, real official OpenRouter endpoints, .env unchanged', captures }, null, 2).replaceAll(token, '[redacted-case-token]') + '\n');
console.log('Real provider rejection preserves assessment/review, emits sanitized chat errors, and retries only the saved chat turn.');
